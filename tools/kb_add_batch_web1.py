def main():
    with open(KB, encoding="utf-8") as f:
        kb = json.load(f)
    have = {x["id"] for x in kb["entries"]}
    added = 0
    for x in ENTRIES:
        if x["id"] not in have:
            kb["entries"].append(x)
            added += 1
    with open(KB, "w", encoding="utf-8") as f:
        json.dump(kb, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"added {added}, total {len(kb['entries'])}")


if __name__ == "__main__":
    main()
